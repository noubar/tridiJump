import { createHash } from 'node:crypto';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readTarGzipEntries, readZipEntries } from './archive.ts';
import { CONVERTER_VERSION, FORMAT_VERSION, RETRIEVAL_DATE, SOURCES } from './config.ts';
import { bucketForKey } from './model.ts';
import type { LexicalIndex } from './model.ts';
import { convertDing } from './parse-ding.ts';
import { convertOewn, OEWN_REQUIRED_FILES } from './parse-oewn.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const sourceDirectory = resolve(root, 'lexical-source/archives');
const outputDirectory = resolve(root, 'public/lexical-data');

async function verifiedSource(source: typeof SOURCES[keyof typeof SOURCES]): Promise<Buffer> {
  const path = resolve(sourceDirectory, source.file);
  const data = await readFile(path).catch(() => { throw new Error(`Missing lexical source ${path}. Run npm run lexicon:fetch.`); });
  const actual = createHash('sha256').update(data).digest('hex');
  if (actual !== source.sha256) throw new Error(`${source.name} checksum mismatch: expected ${source.sha256}, received ${actual}.`);
  return data;
}

async function writeIndex(name: string, index: LexicalIndex, senseLimit: number): Promise<{ bytes: number; chunks: number }> {
  const buckets = new Map<string, Record<string, string[][]>>();
  for (const key of [...index.keys()].sort()) {
    const bucket = bucketForKey(key);
    const entries = buckets.get(bucket) ?? {};
    entries[key] = index.get(key)!.slice(0, senseLimit).map((sense) => sense.slice(0, 8));
    buckets.set(bucket, entries);
  }
  let bytes = 0;
  for (const [bucket, entries] of [...buckets].sort(([left], [right]) => left.localeCompare(right))) {
    const json = `${JSON.stringify({ format: FORMAT_VERSION, entries })}\n`;
    const path = resolve(outputDirectory, name, `${bucket}.json`);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, json);
    bytes += Buffer.byteLength(json);
  }
  return { bytes, chunks: buckets.size };
}

async function main(): Promise<void> {
  const [oewnArchive, dingArchive] = await Promise.all([verifiedSource(SOURCES.oewn), verifiedSource(SOURCES.ding)]);
  const oewnRaw = readZipEntries(oewnArchive, new Set(OEWN_REQUIRED_FILES));
  const oewnFiles = new Map([...oewnRaw].map(([name, data]) => [name, data.toString('utf8')]));
  const dingFiles = readTarGzipEntries(dingArchive, new Set(['de-en.txt']));
  const oewn = convertOewn(oewnFiles);
  const ding = convertDing(dingFiles.get('de-en.txt')!.toString('utf8'));

  await rm(outputDirectory, { recursive: true, force: true });
  await mkdir(outputDirectory, { recursive: true });
  const [synonyms, de, en] = await Promise.all([
    writeIndex('synonyms', oewn.index, 4),
    writeIndex('translations/de', ding.deToEn, 8),
    writeIndex('translations/en', ding.enToDe, 8),
  ]);
  const provenance = {
    generatedFormatVersion: FORMAT_VERSION,
    converterVersion: CONVERTER_VERSION,
    retrievalDate: RETRIEVAL_DATE,
    sources: [SOURCES.oewn, SOURCES.ding],
    counts: {
      oewnSelectedSynsets: oewn.selectedSynsets,
      oewnIndexedLemmas: oewn.index.size,
      dingNounRecords: ding.nounRecords,
      dingGermanLemmas: ding.deToEn.size,
      dingEnglishLemmas: ding.enToDe.size,
    },
    assets: { synonyms, dingGermanToEnglish: de, dingEnglishToGerman: en },
  };
  await writeFile(resolve(outputDirectory, 'provenance.json'), `${JSON.stringify(provenance, null, 2)}\n`);
  await writeFile(resolve(outputDirectory, 'README.md'), '# Generated lexical assets\n\nThese deterministic browser assets are generated by `npm run lexicon:build` from the verified archives in `lexical-source/archives`. They contain only conservative noun synonyms and bilingual lemma translations. See `THIRD_PARTY_NOTICES.md` and `licenses/`.\n');
  console.log(JSON.stringify(provenance.counts, null, 2));
  console.log(JSON.stringify(provenance.assets, null, 2));
}

await main();
